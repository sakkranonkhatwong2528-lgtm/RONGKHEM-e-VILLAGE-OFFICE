/* =========================================================
   23. DASHBOARD STATISTICS
   ========================================================= */

create or replace function
public.dashboard_stats()

returns json

language sql

stable

security definer

set search_path = public

as $$

    select json_build_object(

        'population',
        (
            select count(*)
            from public.citizens
            where active = true
        ),

        'households',
        (
            select count(*)
            from public.households
            where active = true
        ),

        'elderly',
        (
            select count(*)
            from public.elderly
            where active = true
        ),

        'disabled',
        (
            select count(*)
            from public.disabled_persons
            where active = true
        ),

        'vulnerable',
        (
            select count(*)
            from public.vulnerable_groups
            where active = true
        ),

        'activities',
        (
            select count(*)
            from public.activities
        ),

        'projects',
        (
            select count(*)
            from public.projects
        ),

        'complaints',
        (
            select count(*)
            from public.complaints
        )

    );

$$;


